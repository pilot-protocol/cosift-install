# shellcheck disable=SC2016
AWK_VALIDATE='
{ doc = doc $0 "\n" }
END {
  n = length(doc); depth = 0; instr = 0; started = 0; ok = 1
  for (p = 1; p <= n; p++) {
    c = substr(doc, p, 1)
    if (instr) {
      if (c == "\\") { p++; continue }
      if (c == "\"") instr = 0
      continue
    }
    if (c == "\"") { instr = 1; continue }
    if (c == "{" || c == "[") {
      if (!started && c != "{") ok = 0
      started = 1; depth++
      continue
    }
    if (c == "}" || c == "]") { depth--; if (depth < 0) ok = 0; continue }
    if (c ~ /[ \t\r\n]/) continue
    if (!started) ok = 0
  }
  if (instr || depth != 0 || !started || !ok) exit 1
  exit 0
}
'

