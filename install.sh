READ_WORD=''
READ_JSON=''

read_state() {
	_path=$1
	READ_WORD=''
	READ_JSON=''
	if [ -n "$PY" ]; then
		_out=$(py_read "$_path" 2>/dev/null)
		if [ -z "$_out" ]; then
			READ_WORD=malformed
		else
			READ_WORD=$(printf '%s\n' "$_out" | sed -n '1p')
			READ_JSON=$(printf '%s\n' "$_out" | sed -n '2p')
		fi
	else
		if ! json_valid "$_path"; then
			READ_WORD=malformed
		else
			_ob=$(json_get "$_path" onboarded)
			READ_WORD=$(state_word_from_raw "$_ob")
			_ver=$(json_get "$_path" version)
			_hc=$(json_get "$_path" harnesses_configured)
			_at=$(json_get "$_path" onboarded_at)
			case $_hc in
			'['*) : ;;
			*) _hc='[]' ;;
			esac
			case $_at in
			'"'*) : ;;
			*) _at=null ;;
			esac
			if [ -z "$_ver" ]; then
				_ver=null
			fi
			if [ "$READ_WORD" = malformed ]; then
				_ob=null
			elif [ -z "$_ob" ]; then
				_ob=false
			fi
			READ_JSON=$(printf '{"state_path":"%s","present":true,"onboarded":%s,"version":%s,"harnesses_configured":%s,"onboarded_at":%s%s}' \
				"$(json_escape "$_path")" "$_ob" "$_ver" "$_hc" "$_at" \
				"$(if [ "$READ_WORD" = malformed ]; then printf ',"malformed":true'; fi)")
		fi
	fi
	if [ "$READ_WORD" = malformed ] && [ -z "$READ_JSON" ]; then
		READ_JSON=$(printf '{"state_path":"%s","present":true,"onboarded":null,"version":null,"harnesses_configured":[],"onboarded_at":null,"malformed":true}' \
			"$(json_escape "$_path")")
	fi
}

absent_json() {
	printf '{"state_path":"%s","present":false,"onboarded":null,"version":null,"harnesses_configured":[],"onboarded_at":null}' \
		"$(json_escape "$1")"
}

authoritative_file() {
	if [ -f "$STATE_FILE" ]; then
		printf '%s' "$STATE_FILE"
	elif [ -f "$OWN_FILE" ]; then
		printf '%s' "$OWN_FILE"
	fi
}

backup_path() {
	_base="$1.cosift-backup-$(date -u '+%Y%m%dT%H%M%SZ')"
	_try=$_base
	_n=2
	while [ -e "$_try" ]; do
		_try="$_base-$_n"
		_n=$((_n + 1))
	done
	printf '%s' "$_try"
}

# ------------------------------------------------------------ subcommands --

cmd_status() {
	_json=0
	while [ $# -gt 0 ]; do
		case $1 in
		--json) _json=1 ;;
		-h | --help)
			usage
			exit 0
			;;
		*) fail "$EX_USAGE" "status: unknown argument: $1" ;;
		esac
		shift
	done

	_file=$(authoritative_file)
	if [ -z "$_file" ]; then
		if [ "$_json" = 1 ]; then
			absent_json "$STATE_FILE"
			printf '\n'
		else
			printf 'unknown\n'
		fi
		warn "no state file at $STATE_FILE: Cosift may have been configured by hand; run \"$PROG complete\" once the interview is finished"
		exit "$EX_UNKNOWN"
	fi

	read_state "$_file"
	if [ "$_json" = 1 ]; then
		printf '%s\n' "$READ_JSON"
	else
		printf '%s\n' "$READ_WORD"
	fi
	case $READ_WORD in
	pending) exit 0 ;;
	done | declined) exit "$EX_DONE" ;;
	*)
		warn "state file is not parseable: $_file"
		exit "$EX_MALFORMED"
		;;
	esac
}

cmd_complete() {
	_force=0
	_value=true
	while [ $# -gt 0 ]; do
		case $1 in
		--force) _force=1 ;;
		--declined) _value=declined ;;
		-h | --help)
			usage
			exit 0
			;;
		*) fail "$EX_USAGE" "complete: unknown argument: $1" ;;
		esac
		shift
	done

	_want='done'
	if [ "$_value" = declined ]; then
		_want=declined
	fi

	_file=$(authoritative_file)
	if [ -n "$_file" ]; then
		read_state "$_file"
		if [ "$READ_WORD" = malformed ]; then
			warn "refusing to write: state file is not parseable: $_file"
			exit "$EX_MALFORMED"
		fi
		if [ "$READ_WORD" = "$_want" ] && [ "$_force" = 0 ]; then
			printf 'already recorded: %s\n' "$_file"
			exit 0
		fi
	else
		_file=$OWN_FILE
	fi

	if [ -z "$PY" ] && [ -f "$_file" ]; then
		awk -v newval=true -v stamp=x -v version=x "$AWK_SET" "$_file" >/dev/null 2>&1
		if [ $? = 3 ]; then
			fail "$EX_MALFORMED" "refusing to edit $_file without python3: the string \"onboarded\" occurs more than once and a blind substitution could corrupt it"
		fi
	fi

	_dir=${_file%/*}
	if [ ! -d "$_dir" ]; then
		if ! mkdir -p "$_dir" 2>/dev/null; then
			fail "$EX_WRITE" "cannot create directory: $_dir"
		fi
		chmod 0700 "$_dir" 2>/dev/null
	fi

	if [ -f "$_file" ]; then
		# At most one backup survives: this runs in the installer's directory,
		# and a dated copy of account_uid per run would pile up there forever.
		for _old in "$_file".cosift-backup-*; do
			if [ -f "$_old" ]; then
				rm -f "$_old" 2>/dev/null
			fi
		done
		_bak=$(backup_path "$_file")
		if ! cp -p "$_file" "$_bak" 2>/dev/null; then
			if ! cp "$_file" "$_bak" 2>/dev/null; then
				fail "$EX_WRITE" "cannot create backup: $_bak"
			fi
		fi
		chmod 0600 "$_bak" 2>/dev/null
	else
		_bak=''
	fi

	_stamp=$(date -u '+%Y-%m-%dT%H:%M:%SZ')
	_ver=$(version_string)

	if [ -n "$PY" ]; then
		py_write "$_file" "$_value" "$_stamp" "$_ver"
		_rc=$?
		if [ "$_rc" = 3 ]; then
			warn "refusing to write: state file is not parseable: $_file"
			exit "$EX_MALFORMED"
		fi
		if [ "$_rc" != 0 ]; then
			fail "$EX_WRITE" "write failed: $_file"
		fi
	else
		posix_write "$_file" "$_value" "$_stamp" "$_ver"
	fi

	read_state "$_file"
	if [ "$READ_WORD" != "$_want" ]; then
		fail "$EX_WRITE" "write did not take effect: $_file"
	fi

	if [ -n "$_bak" ]; then
		printf 'recorded: %s onboarded=%s (backup %s)\n' "$_file" "$_value" "$_bak"
	else
		printf 'recorded: %s onboarded=%s\n' "$_file" "$_value"
	fi
	exit 0
}

posix_write() {
	_pw_file=$1
	_pw_value=$2
	_pw_stamp=$3
	_pw_ver=$4
	_pw_dir=${_pw_file%/*}
	TMPF="$_pw_dir/.cosift-onboarding.tmp.$$"

	if [ "$_pw_value" = declined ]; then
		_pw_new='"declined"'
	else
		_pw_new=true
	fi

	if [ -f "$_pw_file" ]; then
		awk -v newval="$_pw_new" -v stamp="$_pw_stamp" -v version="$_pw_ver" \
			"$AWK_SET" "$_pw_file" >"$TMPF" 2>/dev/null
		_pw_rc=$?
		if [ "$_pw_rc" = 3 ]; then
			rm -f "$TMPF"
			TMPF=''
			warn "refusing to edit $_pw_file without python3: the string \"onboarded\" occurs more than once and a blind substitution could corrupt it"
			exit "$EX_MALFORMED"
		fi
		if [ "$_pw_rc" != 0 ]; then
			rm -f "$TMPF"
			TMPF=''
			fail "$EX_WRITE" "write failed: $_pw_file"
		fi
	else
		{
			printf '{\n'
			printf '  "onboarded": %s,\n' "$_pw_new"
			printf '  "onboarded_at": "%s",\n' "$_pw_stamp"
			printf '  "onboarding_version": "%s"\n' "$_pw_ver"
			printf '}\n'
		} >"$TMPF" 2>/dev/null || {
			rm -f "$TMPF"
			TMPF=''
			fail "$EX_WRITE" "write failed: $_pw_file"
		}
	fi

	if ! json_valid "$TMPF"; then
		rm -f "$TMPF"
		TMPF=''
		fail "$EX_WRITE" "refusing to install an unparseable result over $_pw_file"
	fi
	chmod 0600 "$TMPF" 2>/dev/null
	if ! mv "$TMPF" "$_pw_file" 2>/dev/null; then
		rm -f "$TMPF"
		TMPF=''
		fail "$EX_WRITE" "write failed: $_pw_file"
	fi
	TMPF=''
	command -v sync >/dev/null 2>&1 && sync 2>/dev/null
	return 0
}

cmd_paths() {
	_json=0
	while [ $# -gt 0 ]; do
		case $1 in
		--json) _json=1 ;;
		-h | --help)
			usage
			exit 0
			;;
		*) fail "$EX_USAGE" "paths: unknown argument: $1" ;;
		esac
		shift
	done

	_mf=$(manifest_path)
	_source=builtin
	_lines=''
	if [ -n "$_mf" ] && [ -n "$PY" ]; then
		_lines=$(py_manifest_paths "$_mf" 2>/dev/null)
		if printf '%s\n' "$_lines" | grep -q '	.' 2>/dev/null; then
			_source=manifest
		else
			_lines=''
		fi
	fi

	if [ "$_json" = 1 ]; then
		printf '{"source":"%s","manifest_path":' "$_source"
		if [ "$_source" = manifest ]; then
			printf '"%s"' "$(json_escape "$_mf")"
		else
			printf 'null'
		fi
		printf ',"paths":{'
		_first=1
	fi

	for _h in $HARNESS_LIST; do
		_p=''
		if [ "$_source" = manifest ]; then
			_p=$(printf '%s\n' "$_lines" | awk -F'\t' -v h="$_h" '$1==h {print $2; exit}')
		fi
		if [ "$_h" = codex ] && [ -n "${COSIFT_CODEX_SKILLS_DIR:-}" ]; then
			_p=''
		fi
		if [ -n "$_p" ]; then
			_p=$(expand_path "$_p")
		else
			_p=$(default_target "$_h")
		fi
		if [ "$_json" = 1 ]; then
			if [ "$_first" = 0 ]; then
				printf ','
			fi
			_first=0
			printf '"%s":"%s"' "$_h" "$(json_escape "$_p")"
		else
			printf '%s\t%s\n' "$_h" "$_p"
		fi
	done

	if [ "$_json" = 1 ]; then
		printf '}}\n'
	fi
	exit 0
}

