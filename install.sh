# A directory reached through a symlink is a normal dotfiles layout and is fine to write
# into; a symlink that is not a directory is something else wearing a directory's name.
onboarding_mkdir() {
	if [ -d "$1" ]; then return 0; fi
	if [ -L "$1" ] || [ -e "$1" ]; then
		warn "$1 exists and is not a directory; leaving it alone."
		return 1
	fi
	if ! mkdir -p "$1"; then
		err "could not create $1"
		return 1
	fi
	chmod 755 "$1" 2>/dev/null
	return 0
}

# Writing a file in place follows both symlinks and hard links, so either one planted at a
# path we write would clobber its target - an always-loaded instruction file, or whatever a
# dotfile manager put in ~/.local/bin - while the install reported success. We refuse a
# symlink outright, because replacing it would destroy a link the user made on purpose.
onboarding_refuse_symlink() {
	if [ ! -L "$1" ]; then return 0; fi
	warn "$1 is a symlink; leaving it and whatever it points at alone."
	warn "remove the symlink and re-run if you want the interview there."
	return 1
}

# rename(2) replaces the directory entry, so it never writes through a link and never
# shares an inode with one. The temp file is a sibling so the rename stays on one device.
onboarding_place() {
	_pdst=$2
	_ptmp="$(dirname "$_pdst")/.cosift-onboarding.$$"
	rm -f "$_ptmp"
	if ! cp "$1" "$_ptmp"; then
		rm -f "$_ptmp"
		err "could not write $_ptmp"
		return 1
	fi
	chmod "$3" "$_ptmp" 2>/dev/null
	if ! mv -f "$_ptmp" "$_pdst"; then
		rm -f "$_ptmp"
		err "could not write $_pdst"
		return 1
	fi
	return 0
}

# prefix + body, under $TMPD, is what every comparison below is made against.
onboarding_compose() {
	_oc="$TMPD/onboarding.$1"
	if [ ! -f "$_oc" ]; then
		if ! { onboarding_prefix "$1" && onboarding_body; } >"$_oc"; then
			rm -f "$_oc"
			err "this installer carries no onboarding interview for $1."
			return 1
		fi
	fi
	printf '%s\n' "$_oc"
}

onboarding_cmd_compose() {
	_occ="$TMPD/onboarding.cmd"
	if [ ! -f "$_occ" ]; then
		if ! onboarding_cmd_source >"$_occ"; then
			rm -f "$_occ"
			err "this installer carries no onboarding state command."
			return 1
		fi
	fi
	printf '%s\n' "$_occ"
}

onboarding_state() {
	_os=$(onboarding_path "$1") || return 1
	if [ ! -e "$_os" ]; then
		printf '%s\n' absent
		return 0
	fi
	_ow=$(onboarding_compose "$1") || return 1
	if [ ! -f "$_os" ]; then
		printf '%s\n' foreign
		return 0
	fi
	if cmp -s "$_os" "$_ow"; then
		printf '%s\n' ours
		return 0
	fi
	# An artifact we shipped in an earlier release is still ours to replace: without this
	# every version bump would back up our own file and report it as someone else's.
	if grep -Fq "$ONBOARDING_MARK" "$_os" 2>/dev/null; then
		printf '%s\n' stale
		return 0
	fi
	printf '%s\n' foreign
}

# opencode scans command/ as well as commands/, so a rival file of our name in the
# singular directory would register /cosift-onboarding twice.
onboarding_opencode_rival() {
	if [ -e "$OPENCODE_DIR/command/cosift-onboarding.md" ]; then
		printf '%s\n' "$OPENCODE_DIR/command/cosift-onboarding.md"
		return 0
	fi
	return 1
}

onboarding_install() {
	if [ "$1" = opencode ] && _orival=$(onboarding_opencode_rival); then
		warn "opencode reads both command/ and commands/, so installing our interview would"
		warn "give two files the same command name. This one is already there:"
		warn "  $_orival"
		warn "we left it untouched; rename or remove it, then re-run with --onboarding."
		return 1
	fi
	_op=$(onboarding_path "$1") || return 1
	onboarding_refuse_symlink "$_op" || return 1
	if [ -e "$_op" ] && [ ! -f "$_op" ]; then
		warn "$_op is not a regular file; leaving it alone."
		return 1
	fi
	_oart=$(onboarding_compose "$1") || return 1
	_ost=$(onboarding_state "$1") || return 1
	if [ "$_ost" = ours ]; then
		chmod 644 "$_op" 2>/dev/null
		ok "interview: already up to date - left untouched"
		return 0
	fi
	if [ "$_ost" = foreign ] && ! ensure_backup "$_op"; then return 1; fi
	if ! onboarding_mkdir "$(onboarding_shared_parent "$1")"; then return 1; fi
	_odir=$(onboarding_owned_dir "$1")
	if [ -n "$_odir" ] && ! onboarding_mkdir "$_odir"; then return 1; fi
	onboarding_place "$_oart" "$_op" 644 || return 1
	if ! cmp -s "$_op" "$_oart"; then
		err "$_op does not match the interview we meant to write."
		return 1
	fi
	ok "interview: wrote $(dim "$_op")"
	if [ "$_ost" = foreign ]; then
		ok "interview: replaced a file we did not write; backup $(dim "$BACKUP_PATH")"
	fi
	return 0
}

onboarding_remove() {
	_op=$(onboarding_path "$1") || return 1
	if [ -L "$_op" ]; then
		warn "$_op is a symlink, so it is not the file we wrote; leaving it alone."
		return 0
	fi
	if [ ! -e "$_op" ]; then
		say "    $(dim "$_op: nothing to remove")"
		return 0
	fi
	if [ ! -f "$_op" ]; then
		warn "$_op is not a regular file; leaving it alone."
		return 1
	fi
	BACKUP_PATH=""
	if [ "$(onboarding_state "$1")" = foreign ] && ! ensure_backup "$_op"; then return 1; fi
	if ! rm -f "$_op"; then
		err "could not remove $_op"
		return 1
	fi
	ok "removed $(dim "$_op")"
	if [ -n "$BACKUP_PATH" ]; then
		say "    backup $(dim "$BACKUP_PATH")"
	fi
	# The shared parent is never ours to remove.
	_odir=$(onboarding_owned_dir "$1")
	if [ -n "$_odir" ]; then
		rmdir "$_odir" 2>/dev/null || :
	fi
	return 0
}

# A copy we shipped in an earlier release, matched the same way the artifacts are.
