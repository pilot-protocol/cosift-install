py_read() {
	"$PY" - "$1" <<'PYEOF'
import json, sys
try:
    from collections import OrderedDict
except ImportError:
    OrderedDict = dict
try:
    text_type = basestring
except NameError:
    text_type = str

path = sys.argv[1]
try:
    fh = open(path, 'rb')
    raw = fh.read()
    fh.close()
    doc = json.loads(raw.decode('utf-8'), object_pairs_hook=OrderedDict)
except Exception:
    sys.stdout.write('malformed\n')
    sys.exit(0)
if not isinstance(doc, dict):
    sys.stdout.write('malformed\n')
    sys.exit(0)

ob = doc.get('onboarded', False)
if ob is True:
    word = 'done'
elif ob is False or ob is None:
    word = 'pending'
elif isinstance(ob, text_type) and ob.strip().lower() == 'declined':
    word = 'declined'
else:
    word = 'malformed'

out = OrderedDict()
out['state_path'] = path
out['present'] = True
out['onboarded'] = None if word == 'malformed' else ob
out['version'] = doc.get('version')
hc = doc.get('harnesses_configured')
out['harnesses_configured'] = hc if isinstance(hc, list) else []
oa = doc.get('onboarded_at')
out['onboarded_at'] = oa if isinstance(oa, text_type) else None
if word == 'malformed':
    out['malformed'] = True
sys.stdout.write(word + '\n')
sys.stdout.write(json.dumps(out, separators=(',', ':')) + '\n')
PYEOF
}

