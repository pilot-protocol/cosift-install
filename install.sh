			-e "s|\${HERMES_HOME}|$(hermes_home)|g" \
			-e "s|\$HERMES_HOME|$(hermes_home)|g" \
			-e "s|\${HOME}|$HOME|g" \
			-e "s|\$HOME|$HOME|g" \
			-e "s|^~/|$HOME/|")
		;;
	esac
	printf '%s' "$_p"
}

