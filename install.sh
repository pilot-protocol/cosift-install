#!/bin/sh
# cosift-install - register the Cosift remote MCP server with your AI harnesses.
#
# WHAT IT DOES
#   Adds a streamable-HTTP MCP server named "cosift" to every harness you select
#   (Claude Code, OpenAI Codex CLI, opencode), authenticated by a static header
#   "Authorization: Bearer ck_<keyid>_<secret>".  A token is either recovered from
#   a harness config you already have, or minted through an email + 6-digit-code
#   flow against the Cosift auth service.
#
# WHAT IT WRITES
#   claude    ~/.claude.json            (via `claude mcp add --scope user`, never by hand)
#   codex     ${CODEX_HOME:-~/.codex}/config.toml   (marker-delimited block, appended)
#   opencode  ${XDG_CONFIG_HOME:-~/.config}/opencode/opencode.json[c]  (via `opencode mcp add`)
#   state     ${XDG_CONFIG_HOME:-~/.config}/cosift/state.json          (mode 0600)
#   CLI       ${XDG_CONFIG_HOME:-~/.config}/cosift/community-session.json (mode 0600)
#             when a compatible cosift binary is installed; --no-cli skips this
#   Every file touched is copied to <path>.cosift-backup-<UTC timestamp> first.
#
# THESE FILES THEN HOLD A LIVE CREDENTIAL.  Treat them like a password store.
#
# THE ONBOARDING INTERVIEW (optional, written only if you say yes)
#   claude    ~/.claude/skills/cosift-onboarding/SKILL.md
#   codex     ${COSIFT_CODEX_SKILLS_DIR:-~/.agents/skills}/cosift-onboarding/SKILL.md
#   opencode  ${XDG_CONFIG_HOME:-~/.config}/opencode/commands/cosift-onboarding.md
#   command   ~/.local/bin/cosift-onboarding                     (mode 0755)
#   claude    ~/.claude/settings.json - one SessionStart hook and the cosift tool
#             permissions are appended; every other key is left as it was.
#   These carry NO credential.  The files are 0644 and their directories 0755.
#   Claude Code starts the interview by itself; elsewhere you type its name.
#   --onboarding installs them without asking; --no-onboarding skips them.
#   At the end you are asked once whether to open a harness on a prompt that runs
#   the interview; --no-launch and --yes skip that question.
#
# HOW TO UNDO
#   Re-run with --uninstall: the cosift entry is removed from each harness, the
#   interview files above are removed, and the state file is deleted.  Backups are
#   left in place.  Uninstalling does NOT revoke the token server-side - revoke it
#   from your Cosift account.
#
# USAGE
#   curl -fsSL <installer-url> | sh
#   curl -fsSL <installer-url> | sh -s -- --dry-run
#   sh install.sh --harness=claude,codex --yes
#
# POSIX sh only (this runs under dash via curl | sh).  No bashisms.

