	fi
}

claude_add() {
	_tok=$1
	if ! have_cmd claude; then
		err "claude is not on PATH, so its config cannot be written safely."
		err "install Claude Code and re-run, or add the server manually:"
		claude_manual_help
		return 1
	fi
	if ! claude_json_ok; then
		claude_refuse_malformed
		return 1
	fi
	# Backup precedes every CLI call: `claude mcp list` itself rewrites this file, and a
	# config it refuses to parse is quarantined and replaced before we ever see it.
	if ! ensure_backup "$CLAUDE_JSON"; then return 1; fi
	_bak=$BACKUP_PATH
	claude_topkeys >"$TMPD/claude.topkeys.before"
	claude_user_servers >"$TMPD/claude.servers.before"
	claude_quarantine_list >"$TMPD/claude.quarantine.before"
	if claude_is_configured; then
		claude mcp remove cosift --scope user >/dev/null 2>&1
	fi
	# `claude mcp add --header` puts the token in argv; unavoidable for this CLI and
	# accepted only here. --scope user is mandatory: the default "local" scope binds
	# the server to projects["<cwd>"], i.e. whatever directory the installer ran in.
	if [ -n "$COSIFT_EXTRA_HEADER" ]; then
		claude mcp add --transport http --scope user cosift "$COSIFT_MCP_URL" \
			--header "Authorization: Bearer $_tok" \
			--header "$COSIFT_EXTRA_HEADER" >"$TMPD/claude.add" 2>&1
		_rc=$?
	else
		claude mcp add --transport http --scope user cosift "$COSIFT_MCP_URL" \
			--header "Authorization: Bearer $_tok" >"$TMPD/claude.add" 2>&1
		_rc=$?
	fi
	if [ "$_rc" -ne 0 ]; then
		if ! claude_reset_check "$_bak"; then return 1; fi
		err "claude mcp add failed:"
		redact <"$TMPD/claude.add" >&2
		return 1
	fi
	if ! claude_reset_check "$_bak"; then return 1; fi
	if [ -z "$(claude_user_entry)" ]; then
		err "claude reported success but cosift is not in the user scope of $CLAUDE_JSON."
		return 1
	fi
	harden_mode "$CLAUDE_JSON"
	return 0
}

claude_remove() {
	if [ ! -f "$CLAUDE_JSON" ] || ! grep -q '"cosift"' "$CLAUDE_JSON"; then
		say "claude: no cosift entry found, nothing to remove."
		return 0
	fi
	# Losing Claude Code must not make --uninstall impossible; only a real leftover
	# entry is worth blocking on, and then only with instructions.
	if ! have_cmd claude; then
		err "claude is not on PATH, but $CLAUDE_JSON still has a cosift entry."
		err "remove it once Claude Code is available:"
		err "  claude mcp remove cosift --scope user"
		err "or edit $CLAUDE_JSON by hand: delete the \"cosift\" key (and the object"
		err "after it) from the top-level \"mcpServers\" object."
		return 1
	fi
	if ! claude_json_ok; then
		claude_refuse_malformed
		return 1
	fi
	if ! ensure_backup "$CLAUDE_JSON"; then return 1; fi
	claude mcp remove cosift --scope user >"$TMPD/claude.rm" 2>&1
	if [ -n "$(claude_user_entry)" ]; then
		err "cosift is still present in the Claude Code user config after removal:"
		redact <"$TMPD/claude.rm" >&2
		return 1
	fi
	claude_project_dirs >"$TMPD/claude.projdirs" 2>/dev/null || :
	while IFS= read -r _pd; do
		[ -n "$_pd" ] || continue
		if [ -d "$_pd" ]; then
			(cd "$_pd" && claude mcp remove cosift --scope local) >/dev/null 2>&1 || :
		fi
	done <"$TMPD/claude.projdirs"
	claude_project_dirs >"$TMPD/claude.projleft" 2>/dev/null || :
	if [ -s "$TMPD/claude.projleft" ]; then
		err "a cosift entry still holds a live credential in these Claude Code project"
		err "scopes, and we could not remove it:"
		while IFS= read -r _pd; do
			[ -n "$_pd" ] && err "  $_pd"
		done <"$TMPD/claude.projleft"
		err "remove each one with:  cd <dir> && claude mcp remove cosift"
		return 1
	fi
	if [ "$JSON_PARSER" = "awk" ] && grep -q '"cosift"' "$CLAUDE_JSON"; then
		warn "$CLAUDE_JSON still mentions cosift. Without python3 or node we cannot tell"
		warn "whether that is a project-scoped entry holding a live credential. Check with:"
		warn "  claude mcp list"
		return 1
	fi
	return 0
}

claude_manual_help() {
	say "  claude mcp add --transport http --scope user cosift '$COSIFT_MCP_URL' \\"
	say "    --header 'Authorization: Bearer <your ck_ token>'"
}

# ------------------------------------------------- claude code: settings.json

# The interview starts itself from a SessionStart hook, and runs without asking for
# the four cosift tools. Both are appended to a file the user owns and shares with
# every other hook they have, so nothing is ever rewritten in place: we add our entry
# if it is absent, take ours back out on uninstall, and touch nothing else.

claude_settings_usable() {
	detect_json_parser
	if [ "$JSON_PARSER" = awk ]; then
		warn "no python3 or node here, so $CLAUDE_SETTINGS was left alone: a settings file"
		warn "full of other people's hooks is not something to edit with a regex."
		return 1
	fi
	if [ -e "$CLAUDE_SETTINGS" ] && [ ! -f "$CLAUDE_SETTINGS" ]; then
		warn "$CLAUDE_SETTINGS is not a regular file; leaving it alone."
		return 1
	fi
	if [ -f "$CLAUDE_SETTINGS" ] && ! json_parses "$CLAUDE_SETTINGS"; then
		warn "$CLAUDE_SETTINGS does not parse as JSON, so we left it alone."
		return 1
	fi
	return 0
}

# claude_settings_merge <add|remove> <dry|write> -> prints "changed"|"nochange",
# plus " edited" when a cosift hook that is not the one we wrote is in the file.
# Exit 3 means the shape is not what we expect and nothing was touched.
claude_settings_merge() {
	detect_json_parser
	set -- "$CLAUDE_SETTINGS" "$ONBOARDING_CMD hook" "$1" "$2" \
		mcp__cosift__cosift_search mcp__cosift__cosift_lookup \
		mcp__cosift__cosift_request mcp__cosift__cosift_topics \
		"Bash(cosift-onboarding:*)"
	case "$JSON_PARSER" in
	python3)
		python3 -c 'import json, os, sys

file, cmd, mode, write = sys.argv[1], sys.argv[2], sys.argv[3], sys.argv[4]
perms = sys.argv[5:]
MARK = "cosift-onboarding"
ours = {"type": "command", "command": cmd}

try:
    doc = json.load(open(file, encoding="utf-8")) if os.path.exists(file) else {}
except (OSError, ValueError):
    sys.exit(3)
if not isinstance(doc, dict):
    sys.exit(3)


def bucket(parent, key, kind):
    if key not in parent:
        return kind()
    if not isinstance(parent[key], kind):
        sys.exit(3)
    return parent[key]


def hooks_of(entry):
    if isinstance(entry, dict) and isinstance(entry.get("hooks"), list):
        return entry["hooks"]
    return []


def carries(entry):
    return any(isinstance(h, dict) and h.get("command") == cmd for h in hooks_of(entry))


def mentions(entry):
    return any(isinstance(h, dict) and MARK in str(h.get("command", "")) for h in hooks_of(entry))


def is_ours(entry):
    if not isinstance(entry, dict) or list(entry) != ["hooks"]:
        return False
    return entry["hooks"] == [ours]


changed = False
edited = False

if mode == "add":
    hooks = bucket(doc, "hooks", dict)
    starts = bucket(hooks, "SessionStart", list)
    if not any(carries(e) for e in starts):
        starts.append({"hooks": [dict(ours)]})
        changed = True
    perm = bucket(doc, "permissions", dict)
    allow = bucket(perm, "allow", list)
    for p in perms:
        if p not in allow:
            allow.append(p)
            changed = True
    if changed:
        hooks["SessionStart"] = starts
        doc["hooks"] = hooks
        perm["allow"] = allow
        doc["permissions"] = perm
else:
    hooks = doc.get("hooks")
    if isinstance(hooks, dict) and isinstance(hooks.get("SessionStart"), list):
        keep = []
        for e in hooks["SessionStart"]:
            if is_ours(e):
                changed = True
                continue
            if mentions(e):
                edited = True
            keep.append(e)
        if changed:
            if keep:
                hooks["SessionStart"] = keep
            else:
                del hooks["SessionStart"]
                if not hooks:
                    del doc["hooks"]
    perm = doc.get("permissions")
    if isinstance(perm, dict) and isinstance(perm.get("allow"), list):
        keep = [p for p in perm["allow"] if p not in perms]
        if len(keep) != len(perm["allow"]):
            changed = True
            if keep:
                perm["allow"] = keep
            else:
                del perm["allow"]
                if not perm:
                    del doc["permissions"]

if changed and write == "write":
    target = os.path.realpath(file)
    bits = os.stat(target).st_mode & 0o777 if os.path.exists(target) else 0o600
    tmp = target + ".cosift-tmp"
    with open(tmp, "w", encoding="utf-8") as fh:
        fh.write(json.dumps(doc, indent=2, ensure_ascii=False) + "\n")
    os.chmod(tmp, bits)
    os.replace(tmp, target)

sys.stdout.write(("changed" if changed else "nochange") + (" edited" if edited else "") + "\n")' "$@"
		;;
	node)
		node -e 'const fs = require("fs");
const file = process.argv[1], cmd = process.argv[2];
const mode = process.argv[3], write = process.argv[4];
const perms = process.argv.slice(5);
const MARK = "cosift-onboarding";
const ours = {type: "command", command: cmd};
let doc = {};
try {
  if (fs.existsSync(file)) doc = JSON.parse(fs.readFileSync(file, "utf8"));
} catch (e) { process.exit(3); }
const isObj = (v) => v !== null && typeof v === "object" && !Array.isArray(v);
if (!isObj(doc)) process.exit(3);

function bucket(parent, key, wantList) {
  if (!(key in parent)) return wantList ? [] : {};
  const v = parent[key];
  if (wantList ? !Array.isArray(v) : !isObj(v)) process.exit(3);
  return v;
}
const hooksOf = (e) => (isObj(e) && Array.isArray(e.hooks)) ? e.hooks : [];
const carries = (e) => hooksOf(e).some((h) => isObj(h) && h.command === cmd);
const mentions = (e) => hooksOf(e).some(
  (h) => isObj(h) && typeof h.command === "string" && h.command.indexOf(MARK) >= 0);
function isOurs(e) {
  if (!isObj(e)) return false;
  const k = Object.keys(e);
  if (k.length !== 1 || k[0] !== "hooks" || !Array.isArray(e.hooks) || e.hooks.length !== 1) {
    return false;
  }
  const h = e.hooks[0];
  return isObj(h) && Object.keys(h).length === 2 && h.type === "command" && h.command === cmd;
}

let changed = false, edited = false;
if (mode === "add") {
  const hooks = bucket(doc, "hooks", false);
  const starts = bucket(hooks, "SessionStart", true);
  if (!starts.some(carries)) {
    starts.push({hooks: [Object.assign({}, ours)]});
    changed = true;
  }
  const perm = bucket(doc, "permissions", false);
  const allow = bucket(perm, "allow", true);
  for (const p of perms) {
    if (allow.indexOf(p) < 0) { allow.push(p); changed = true; }
  }
  if (changed) {
    hooks.SessionStart = starts;
    doc.hooks = hooks;
    perm.allow = allow;
    doc.permissions = perm;
  }
} else {
  const hooks = doc.hooks;
  if (isObj(hooks) && Array.isArray(hooks.SessionStart)) {
    const keep = [];
    for (const e of hooks.SessionStart) {
      if (isOurs(e)) { changed = true; continue; }
      if (mentions(e)) edited = true;
      keep.push(e);
    }
    if (changed) {
      if (keep.length) hooks.SessionStart = keep;
      else {
        delete hooks.SessionStart;
        if (!Object.keys(hooks).length) delete doc.hooks;
      }
    }
  }
  const perm = doc.permissions;
  if (isObj(perm) && Array.isArray(perm.allow)) {
    const keep = perm.allow.filter((p) => perms.indexOf(p) < 0);
    if (keep.length !== perm.allow.length) {
      changed = true;
      if (keep.length) perm.allow = keep;
      else {
        delete perm.allow;
        if (!Object.keys(perm).length) delete doc.permissions;
      }
    }
  }
}

if (changed && write === "write") {
  let target = file, bits = 0o600;
  if (fs.existsSync(file)) { target = fs.realpathSync(file); bits = fs.statSync(target).mode & 0o777; }
  const tmp = target + ".cosift-tmp";
  fs.writeFileSync(tmp, JSON.stringify(doc, null, 2) + "\n");
  fs.chmodSync(tmp, bits);
  fs.renameSync(tmp, target);
}
process.stdout.write((changed ? "changed" : "nochange") + (edited ? " edited" : "") + "\n");' "$@"
		;;
	*) return 2 ;;
	esac
}

claude_settings_install() {
	if ! claude_settings_usable; then return 1; fi
	if ! _sres=$(claude_settings_merge add dry); then
		warn "$CLAUDE_SETTINGS has a hooks or permissions section shaped in a way we do not"
		warn "recognise, so we left the whole file alone."
		return 1
	fi
	case "$_sres" in
	nochange*)
		CLAUDE_HOOKED=1
		ok "settings: already set up - left untouched"
		return 0
		;;
	esac
	if ! onboarding_mkdir "$(dirname "$CLAUDE_SETTINGS")"; then return 1; fi
	BACKUP_PATH=""
	if ! ensure_backup "$CLAUDE_SETTINGS"; then return 1; fi
	if ! claude_settings_merge add write >/dev/null; then
		warn "could not write $CLAUDE_SETTINGS; it was left as it was."
		return 1
	fi
	CLAUDE_HOOKED=1
	ok "settings: updated $(dim "$CLAUDE_SETTINGS")"
	if [ -n "$BACKUP_PATH" ]; then
		say "    backup $(dim "$BACKUP_PATH")"
	fi
	return 0
}

claude_settings_remove() {
	if [ ! -e "$CLAUDE_SETTINGS" ]; then return 0; fi
	if [ -f "$CLAUDE_SETTINGS" ] &&
		! grep -Eq 'cosift-onboarding|mcp__cosift__' "$CLAUDE_SETTINGS" 2>/dev/null; then
		return 0
	fi
	if ! claude_settings_usable; then return 1; fi
	if ! _sres=$(claude_settings_merge remove dry); then
		warn "$CLAUDE_SETTINGS is not shaped the way we expect; left alone. Remove the"
		warn "cosift-onboarding hook and the mcp__cosift__ permissions by hand."
		return 1
	fi
	case "$_sres" in
	*edited*)
		warn "a cosift-onboarding hook in $CLAUDE_SETTINGS is not the one we wrote, so we"
		warn "left it in place. Remove it by hand if you no longer want it."
		;;
	esac
	case "$_sres" in
	nochange*) return 0 ;;
	esac
	BACKUP_PATH=""
	if ! ensure_backup "$CLAUDE_SETTINGS"; then return 1; fi
	if ! claude_settings_merge remove write >/dev/null; then
		warn "could not write $CLAUDE_SETTINGS; it was left as it was."
		return 1
	fi
	ok "removed our hook and permissions from $(dim "$CLAUDE_SETTINGS")"
	if [ -n "$BACKUP_PATH" ]; then
		say "    backup $(dim "$BACKUP_PATH")"
	fi
	return 0
}

# --------------------------------------------------------- harness: codex cli

codex_detect() {
	if have_cmd codex; then return 0; fi
	[ -f "$CODEX_CONFIG" ]
}

codex_block() {
	if [ -f "$CODEX_CONFIG" ]; then
		awk '
			/^# >>> cosift/ { ins = 1; next }
			/^# <<< cosift/ { ins = 0; next }
			ins { print }
		' "$CODEX_CONFIG" 2>/dev/null
	fi
}

codex_recover_token() {
	codex_block | grep -Eo "$TOKEN_RE" 2>/dev/null
}

codex_has_marker_block() {
	[ -f "$CODEX_CONFIG" ] && grep -q '^# >>> cosift' "$CODEX_CONFIG"
}

codex_is_configured() {
	codex_has_marker_block
}

# Our entry, in our block: a cosift table outside our markers belongs to someone else.
codex_up_to_date() {
	codex_has_marker_block || return 1
	_b=$(codex_block)
	case "$_b" in
	*"$COSIFT_MCP_URL"*) ;;
	*) return 1 ;;
	esac
	case "$_b" in
	*"Bearer $1"*) return 0 ;;
	esac
	return 1
}

# Non-zero when an [mcp_servers.cosift] table exists outside our markers: a second
# table of the same name is a TOML parse error, so we refuse rather than corrupt.
# [mcp_servers."cosift"] and [ mcp_servers . cosift ] are that same table in TOML.
codex_foreign_table() {
	if [ ! -f "$CODEX_CONFIG" ]; then return 1; fi
	awk '
		/^# >>> cosift/ { ins = 1; next }
		/^# <<< cosift/ { ins = 0; next }
		{
			h = $0
			gsub("[\"\047 \t]", "", h)
			if (h ~ /^\[/) {
				if (!ins && h ~ /^\[mcp_servers\.cosift[].]/) bad = 1
				tbl = h
				next
			}
			if (!ins && tbl == "[mcp_servers]" && h ~ /^cosift=/) bad = 1
			if (!ins && tbl == "" && h ~ /^mcp_servers\.cosift=/) bad = 1
		}
		END { exit(bad ? 0 : 1) }
	' "$CODEX_CONFIG"
}

# A cosift server declared twice makes codex refuse to start at all, so this is checked
# on the file we wrote even when the codex binary is not around to check it for us.
# Quoting and padding are normalised away: they name the same TOML table.
codex_duplicate_table() {
	awk '
		/^[ \t]*\[/ {
			h = $0
			sub(/[ \t]*$/, "", h)
			gsub("[\"\047 \t]", "", h)
			tbl = h
			if (h ~ /^\[mcp_servers\.cosift[].]/ && seen[h]++) dup = 1
			next
		}
		{
			h = $0
			gsub("[\"\047 \t]", "", h)
			if (tbl == "[mcp_servers]" && h ~ /^cosift=/) dup = 1
			if (tbl == "" && h ~ /^mcp_servers\.cosift=/) dup = 1
		}
		END { exit(dup ? 0 : 1) }
	' "$1"
}

# A table header that never closes means the file is already unparseable; appending to
# it would bury the real error under ours. A line that starts with "[" inside a
# multi-line string or a multi-line array is not a header, so it is not our business.
codex_config_sane() {
	if [ ! -f "$CODEX_CONFIG" ]; then return 0; fi
	awk '
		function odd(s, d,   n, i) {
			n = 0
			i = index(s, d)
			while (i) { n++; s = substr(s, i + length(d)); i = index(s, d) }
			return n % 2
		}
		{
			if (inml) { if (odd($0, "\"\"\"")) inml = 0; next }
			if (odd($0, "\"\"\"")) { inml = 1; next }
			if ($0 ~ /^[ \t]*\[/ && $0 !~ /]/) bad = 1
		}
		END { exit(bad ? 1 : 0) }
	' "$CODEX_CONFIG"
}

# The line number of an opening marker with no closing marker after it.
codex_unterminated_marker() {
	if [ ! -f "$CODEX_CONFIG" ]; then return 0; fi
	awk '
		/^# >>> cosift/ { o = NR; next }
		/^# <<< cosift/ { o = 0; next }
		END { if (o) print o }
	' "$CODEX_CONFIG"
}

codex_refuse_unterminated() {
	err "$CODEX_CONFIG opens our block at line $1 and never closes it:"
	err "  line $1: $CODEX_MARK_OPEN"
	err "  expected somewhere after it: $CODEX_MARK_CLOSE"
	err "without the closing marker we cannot tell where our block ends, and removing"
	err "it would delete everything from line $1 to the end of the file. Inspect lines"
	err "$1-$2, put the closing marker back after the last cosift line, then re-run."
}

codex_server_names() {
	if [ -f "$1" ]; then
		grep -Eo '^[ 	]*\[mcp_servers\.[A-Za-z0-9_-]+\]' "$1" 2>/dev/null |
			sed -e 's/.*\.\([A-Za-z0-9_-]*\)\]/\1/'
	fi
}

codex_strip_block() {
	awk '
		/^[ \t]*$/ { if (!skip) pending = pending $0 "\n"; next }
		/^# >>> cosift/ { skip = 1; pending = ""; next }
		/^# <<< cosift/ { if (skip) { skip = 0; next } }
		{ if (!skip) { printf "%s", pending; pending = ""; print } }
		# An unclosed block would otherwise mean "delete to EOF"; callers refuse instead.
		END { if (skip) exit 1; printf "%s", pending }
	' "$1"
}

codex_write_block() {
	printf '%s\n' "$CODEX_MARK_OPEN" >>"$1"
	printf '[mcp_servers.cosift]\n' >>"$1"
	printf 'url = "%s"\n' "$COSIFT_MCP_URL" >>"$1"
	printf '[mcp_servers.cosift.http_headers]\n' >>"$1"
	printf 'Authorization = "Bearer %s"\n' "$2" >>"$1"
	if [ -n "$COSIFT_EXTRA_HEADER" ]; then
		_hn=${COSIFT_EXTRA_HEADER%%:*}
		_hv=${COSIFT_EXTRA_HEADER#*:}
		_hv=${_hv# }
		printf '%s = "%s"\n' "$_hn" "$_hv" >>"$1"
	fi
	printf '%s\n' "$CODEX_MARK_CLOSE" >>"$1"
}

codex_cli_ok() {
	have_cmd codex && codex mcp list >/dev/null 2>&1
}

codex_add() {
	_tok=$1
	if ! codex_config_sane; then
		err "$CODEX_CONFIG has an unterminated table header, so it is not valid TOML."
		err "we will not append to a file codex already cannot read. Fix the header"
		err "(look for a line starting with '[' that never closes) and re-run."
		return 1
	fi
	if codex_foreign_table; then
		err "$CODEX_CONFIG already declares [mcp_servers.cosift] outside our markers."
		err "adding a second table of that name would make the file unparseable."
		err "remove or rename the existing table, then re-run."
		return 1
	fi
	_open=$(codex_unterminated_marker)
	if [ -n "$_open" ]; then
		codex_refuse_unterminated "$_open" "$(wc -l <"$CODEX_CONFIG" | tr -d ' ')"
		return 1
	fi
	if ! ensure_backup "$CODEX_CONFIG"; then return 1; fi
	_bak=$BACKUP_PATH
	_cli_before=1
	if codex_cli_ok; then _cli_before=0; fi
	codex_server_names "$CODEX_CONFIG" >"$TMPD/codex.before"
	_new="$TMPD/codex.toml"
	: >"$_new"
	chmod 600 "$_new" 2>/dev/null
	if [ -f "$CODEX_CONFIG" ]; then
		if ! codex_strip_block "$CODEX_CONFIG" >"$_new"; then
			err "could not rewrite $CODEX_CONFIG"
			return 1
		fi
		if [ -s "$_new" ]; then printf '\n' >>"$_new"; fi
	fi
	codex_write_block "$_new" "$_tok"
	if [ ! -d "$CODEX_HOME_DIR" ]; then
		if ! mkdir -p "$CODEX_HOME_DIR"; then
			err "could not create $CODEX_HOME_DIR"
			return 1
		fi
	fi
	if [ -f "$CODEX_CONFIG" ]; then
		if ! cp "$_new" "$CODEX_CONFIG"; then
			err "could not write $CODEX_CONFIG"
			return 1
		fi
	else
		if ! cp "$_new" "$CODEX_CONFIG"; then
			err "could not write $CODEX_CONFIG"
			return 1
		fi
		chmod 600 "$CODEX_CONFIG" 2>/dev/null
	fi
	if ! grep -q '^\[mcp_servers\.cosift\]' "$CODEX_CONFIG" ||
		! codex_has_marker_block; then
		err "the cosift block is not present in $CODEX_CONFIG after writing it."
		restore_backup "$CODEX_CONFIG" "$_bak"
		return 1
	fi
	if codex_duplicate_table "$CODEX_CONFIG"; then
		err "$CODEX_CONFIG declares [mcp_servers.cosift] twice after our change, which"
		err "codex reads as a duplicate key and refuses to start on; restoring the backup."
		err "remove or rename the cosift table you already had, then re-run."
		restore_backup "$CODEX_CONFIG" "$_bak"
		return 1
	fi
	codex_server_names "$CODEX_CONFIG" >"$TMPD/codex.after"
	while IFS= read -r _name; do
		if [ -z "$_name" ] || [ "$_name" = "cosift" ]; then continue; fi
		if ! grep -q "^$_name\$" "$TMPD/codex.after"; then
			err "the MCP server '$_name' disappeared from $CODEX_CONFIG."
			restore_backup "$CODEX_CONFIG" "$_bak"
			return 1
		fi
	done <"$TMPD/codex.before"
	if [ "$_cli_before" -eq 0 ] && ! codex_cli_ok; then
		err "codex can no longer read its config after our change; restoring the backup."
		restore_backup "$CODEX_CONFIG" "$_bak"
		return 1
	fi
	harden_mode "$CODEX_CONFIG"
	return 0
}

codex_remove() {
	if [ ! -f "$CODEX_CONFIG" ]; then
		say "codex: no config at $CODEX_CONFIG, nothing to remove."
		return 0
	fi
	if ! codex_has_marker_block; then
		if codex_foreign_table; then
			err "$CODEX_CONFIG has an [mcp_servers.cosift] table we did not write."
			err "leaving it alone - remove it by hand if you want it gone."
			return 1
		fi
		say "codex: no cosift block found, nothing to remove."
		return 0
	fi
	_open=$(codex_unterminated_marker)
	if [ -n "$_open" ]; then
		codex_refuse_unterminated "$_open" "$(wc -l <"$CODEX_CONFIG" | tr -d ' ')"
		return 1
	fi
	if ! ensure_backup "$CODEX_CONFIG"; then return 1; fi
	_bak=$BACKUP_PATH
	_new="$TMPD/codex.rm.toml"
	if ! codex_strip_block "$CODEX_CONFIG" >"$_new"; then
		err "could not rewrite $CODEX_CONFIG"
		return 1
	fi
	if ! cp "$_new" "$CODEX_CONFIG"; then
		err "could not write $CODEX_CONFIG"
		return 1
	fi
	if codex_has_marker_block || grep -q '^\[mcp_servers\.cosift\]' "$CODEX_CONFIG"; then
		err "the cosift block survived removal; restoring the backup."
		restore_backup "$CODEX_CONFIG" "$_bak"
		return 1
	fi
	if have_cmd codex && ! codex mcp list >/dev/null 2>&1; then
		err "codex cannot read its config after removal; restoring the backup."
		restore_backup "$CODEX_CONFIG" "$_bak"
		return 1
	fi
	return 0
}

