find_python() {
	if [ "${COSIFT_ONBOARDING_NO_PYTHON:-0}" != 0 ]; then
		PY=''
		return 1
	fi
	for _c in python3 python; do
		if command -v "$_c" >/dev/null 2>&1; then
			if "$_c" -c 'import json,sys;sys.exit(0 if sys.version_info[0]>=2 else 1)' >/dev/null 2>&1; then
				PY=$_c
				return 0
