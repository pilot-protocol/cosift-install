	"$PY" - "$1" "$2" "$3" "$4" <<'PYEOF'
import json, os, sys
try:
    from collections import OrderedDict
except ImportError:
    OrderedDict = dict

path, value, stamp, version = sys.argv[1], sys.argv[2], sys.argv[3], sys.argv[4]
doc = OrderedDict()
if os.path.exists(path):
    try:
        fh = open(path, 'rb')
        raw = fh.read()
        fh.close()
        doc = json.loads(raw.decode('utf-8'), object_pairs_hook=OrderedDict)
    except Exception:
        sys.exit(3)
    if not isinstance(doc, dict):
        sys.exit(3)

doc['onboarded'] = True if value == 'true' else 'declined'
doc['onboarded_at'] = stamp
doc['onboarding_version'] = version

directory = os.path.dirname(path) or '.'
tmp = os.path.join(directory, '.cosift-onboarding.tmp.%d' % os.getpid())
data = (json.dumps(doc, indent=2) + '\n').encode('utf-8')
fd = os.open(tmp, os.O_WRONLY | os.O_CREAT | os.O_TRUNC, 0o600)
try:
    handle = os.fdopen(fd, 'wb')
    handle.write(data)
    handle.flush()
    os.fsync(handle.fileno())
    handle.close()
except Exception:
    try:
        os.unlink(tmp)
    except Exception:
        pass
    raise
os.chmod(tmp, 0o600)
os.rename(tmp, path)
try:
    dfd = os.open(directory, os.O_RDONLY)
    os.fsync(dfd)
    os.close(dfd)
except Exception:
    pass
PYEOF
}

py_manifest_paths() {
	"$PY" - "$1" "$HARNESS_LIST" <<'PYEOF'
import json, sys

SOURCE_KEYS = ('install_path', 'target_path', 'target', 'destination', 'dest', 'path', 'install')
NAME_KEYS = ('harness', 'name', 'id', 'harness_name')
GROUP_KEYS = ('harnesses', 'artifacts', 'files', 'targets', 'entries')

path = sys.argv[1]
wanted = sys.argv[2].split()
try:
    fh = open(path, 'rb')
    manifest = json.loads(fh.read().decode('utf-8'))
    fh.close()
except Exception:
    sys.exit(1)


def pick(entry, keys):
    for key in keys:
        value = entry.get(key)
        if isinstance(value, str) and value:
            return value
    return None


def collect(node, found):
    if isinstance(node, dict):
        for key in GROUP_KEYS:
            child = node.get(key)
            if isinstance(child, dict):
                for name, entry in child.items():
                    if isinstance(entry, dict) and name in wanted:
                        found.setdefault(name, entry)
                return
            if isinstance(child, list):
                collect(child, found)
                return
        for name, entry in node.items():
            if isinstance(entry, dict) and name in wanted:
                found.setdefault(name, entry)
    elif isinstance(node, list):
        for entry in node:
            if not isinstance(entry, dict):
                continue
            name = pick(entry, NAME_KEYS)
            if name in wanted:
                found.setdefault(name, entry)


found = {}
collect(manifest, found)
for name in wanted:
    entry = found.get(name)
    value = pick(entry, SOURCE_KEYS) if entry else None
    sys.stdout.write(name + '\t' + (value or '') + '\n')
PYEOF
}

