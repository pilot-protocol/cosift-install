	[~]) _p=$HOME ;;
	[~]/*) _p="$HOME/${_p#?/}" ;;
	esac
	case $_p in
	*'$'* | *'~'*)
		_p=$(printf '%s' "$_p" | sed \
			-e "s|\${XDG_CONFIG_HOME:-~/.config}|$(cfg_home)|g" \
			-e "s|\${XDG_CONFIG_HOME:-\$HOME/.config}|$(cfg_home)|g" \
			-e "s|\${XDG_CONFIG_HOME}|$(cfg_home)|g" \
			-e "s|\$XDG_CONFIG_HOME|$(cfg_home)|g" \
			-e "s|\${HERMES_HOME:-~/.hermes}|$(hermes_home)|g" \
