# ------------------------------------------------------------------- the flow

# The value lands in a curl -K config line and in a TOML basic string, where a newline
# is a new curl directive (token exfiltration) and a quote or backslash silently
# rewrites the header. Neither file format has an escape we can rely on, so the only
# safe answer is to refuse anything that is not a plain header.
check_extra_header() {
	case "$COSIFT_EXTRA_HEADER" in
	*"$NL"* | *"$CR"*)
		die "$EX_USAGE" "COSIFT_EXTRA_HEADER must be a single line: it is written into a curl config file, where a newline starts a new directive."
		;;
	*'"'* | *\\*)
		die "$EX_USAGE" "COSIFT_EXTRA_HEADER must not contain a double quote or a backslash: both are escape characters in the files we write it into."
		;;
	*:*) ;;
	*)
		die "$EX_USAGE" "COSIFT_EXTRA_HEADER must be in \"Name: value\" form."
		;;
	esac
	_hn=${COSIFT_EXTRA_HEADER%%:*}
	case "$_hn" in
	"" | *[!A-Za-z0-9-]*)
		die "$EX_USAGE" "COSIFT_EXTRA_HEADER has an invalid header name '$_hn': expected letters, digits and '-' before the colon."
		;;
	esac
}

preflight() {
	if [ "$OPT_UNINSTALL" -eq 0 ] && ! have_cmd curl; then
		die "$EX_PREFLIGHT" "curl is required but not installed."
	fi
	if [ -z "$HOME" ] || [ ! -d "$HOME" ]; then
		die "$EX_PREFLIGHT" "HOME is not set to a directory; cannot locate any config."
	fi
	if [ "$OPT_DRY_RUN" -eq 0 ] && [ ! -w "$HOME" ]; then
		die "$EX_PREFLIGHT" "$HOME is not writable."
	fi
	if [ -n "$COSIFT_EXTRA_HEADER" ]; then
		check_extra_header
	fi
}

# Asked once, after the harness set is final, and never before every exact path we
# would write has been named.
onboarding_consent() {
	if [ -n "$OPT_ONBOARDING" ] || [ "$OPT_DRY_RUN" -eq 1 ]; then return 0; fi
	if ! tty_usable; then
		OPT_ONBOARDING=0
		say ""
		say "Not setting Cosift up: no terminal to ask for consent on."
		say "Do it whenever you like with:  install.sh --onboarding"
		return 0
	fi
	say ""
	say "${CLR_HEAD}Cosift can set itself up with you${CLR_RESET}: a couple of questions about what you"
	say "work on. To suggest subjects it reads the titles of your recent sessions on this"
	say "machine - they stay here, and only the topics you approve reach Cosift."
	say "It writes these files, none of which holds a credential:"
	for _h in $SELECTED; do
		_op=$(onboarding_path "$_h") || continue
		say "  ${CLR_DIM}$_op${CLR_RESET}"
	done
	say "  ${CLR_DIM}$ONBOARDING_CMD${CLR_RESET}"
	if in_list claude "$SELECTED"; then
		say "  ${CLR_DIM}$CLAUDE_SETTINGS${CLR_RESET}  (one start-up hook and the cosift tools, appended)"
	fi
	say "What every step does: ${CLR_DIM}$WHAT_HAPPENS_URL${CLR_RESET}"
	if ! tty_ask "Set it up? [Y/n]: "; then
		OPT_ONBOARDING=0
		return 0
	fi
	case "$TTY_REPLY" in
	"" | y | Y | yes | YES | Yes) OPT_ONBOARDING=1 ;;
	*) OPT_ONBOARDING=0 ;;
	esac
	return 0
}

select_harnesses() {
	if [ -n "$OPT_HARNESS" ]; then
		SELECTED=""
		for _h in $(printf '%s\n' "$OPT_HARNESS" | tr ',' ' '); do
			if in_list "$_h" "$SELECTED"; then continue; fi
			SELECTED=$(list_add "$SELECTED" "$_h")
			if ! in_list "$_h" "$DETECTED"; then
				warn "$_h was requested but not detected on this machine; trying anyway."
			fi
		done
	elif [ "$OPT_YES" -eq 1 ]; then
		SELECTED=$DETECTED
	else
		require_tty
		say ""
		if ! tty_ask "Configure which? [Enter = all, or e.g. 1,2 or claude,codex]: "; then
			die "$EX_NOTTY" "could not read a selection."
		fi
		_ans=$TTY_REPLY
		case "$_ans" in
		"" | a | A | all | ALL)
			SELECTED=$DETECTED
			;;
		*)
			SELECTED=""
			for _tok in $(printf '%s\n' "$_ans" | tr ',' ' '); do
				case "$_tok" in
				[0-9]*)
					_i=0
					_hit=""
					for _h in $DETECTED; do
						_i=$((_i + 1))
						if [ "$_i" = "$_tok" ]; then _hit=$_h; fi
					done
					if [ -z "$_hit" ]; then
						die "$EX_USAGE" "no harness numbered $_tok in the list above."
					fi
					SELECTED=$(list_add "$SELECTED" "$_hit")
					;;
				*)
					if ! in_list "$_tok" "$DETECTED"; then
						die "$EX_USAGE" "'$_tok' is not one of the detected harnesses."
					fi
					SELECTED=$(list_add "$SELECTED" "$_tok")
					;;
				esac
			done
			if [ -z "$SELECTED" ]; then
				die "$EX_USAGE" "nothing selected."
			fi
			;;
		esac
	fi
	onboarding_consent
	return 0
}

obtain_token() {
	if [ "$OPT_NEW_ACCOUNT" -eq 1 ]; then
		say ""
		say "Signing up for a new account; any credential already on this machine is"
		say "left alone and not reused."
		if ! email_flow; then
			exit "$EX_AUTH"
		fi
		return 0
	fi
	step "Looking for a Cosift credential you already have"
	if try_recover_token; then return 0; fi
	if ! email_flow; then
		exit "$EX_AUTH"
	fi
	return 0
}

# A missing interview must never fail an install whose MCP server is up, so every
# failure here is a warning.
onboarding_step() {
	if [ "$OPT_ONBOARDING" != 1 ]; then return 0; fi
	BACKUP_PATH=""
	if onboarding_install "$1"; then
		ONBOARDED=$(list_add "$ONBOARDED" "$1")
		if [ "$1" = claude ]; then
			claude_settings_install || :
		fi
		return 0
	fi
	warn "the onboarding interview was not installed for $1; the Cosift server itself is"
	warn "configured and working. Add it later with: install.sh --onboarding"
	return 0
}

configure_harnesses() {
	if [ "$OPT_ONBOARDING" = 1 ]; then
		step "Installing the onboarding interview state command"
		if onboarding_cmd_install; then
			ONBOARDED_CMD=$ONBOARDING_CMD
		else
			warn "the interview will still run, but it cannot record that you finished it."
		fi
	fi
	for _h in $SELECTED; do
		step "Configuring $(harness_label "$_h")"
		BACKUP_PATH=""
		if harness_up_to_date "$_h" "$TOKEN"; then
			CONFIGURED=$(list_add "$CONFIGURED" "$_h")
			# "Untouched" covers the contents; an exposed mode on a file already
			# holding the token is still ours to fix.
			harden_mode "$(harness_config_path "$_h")" || :
			ok "already up to date - left untouched"
			onboarding_step "$_h"
			continue
		fi
		if ! harness_add "$_h" "$TOKEN"; then
			err "failed to configure $_h; no further harnesses will be touched."
			if [ -n "$CONFIGURED" ]; then
				err "already configured: $CONFIGURED (remove with --uninstall)"
			fi
			exit "$EX_HARNESS"
		fi
		CONFIGURED=$(list_add "$CONFIGURED" "$_h")
		_cfg=$(harness_config_path "$_h")
		ok "wrote $(dim "$_cfg")"
		if [ -n "$BACKUP_PATH" ]; then
			say "    backup $(dim "$BACKUP_PATH")"
		fi
		onboarding_step "$_h"
	done
}

final_verify() {
	step "Verifying the credential against $COSIFT_MCP_URL"
	_st=$(mcp_initialize "$TOKEN")
	case "$_st" in
	200)
		ok "ok"
		return 0
		;;
	401 | 403)
		mcp_explain "$_st"
		exit "$EX_AUTH"
		;;
	421)
		mcp_explain "$_st"
		exit "$EX_HARNESS"
		;;
	*)
		mcp_explain "$_st"
		warn "the harness configs were written and look correct; this is a transient"
		warn "server or network problem, so nothing was rolled back."
		return 1
		;;
	esac
}

# Reuse the token already in memory. The CLI validates the origin, verifies the
# token against /api/me, and creates a new private, origin-bound session file.
# Never read a credential back out of another application's configuration.
community_cli_step() {
	if [ "$OPT_CLI" = no ]; then return 0; fi
	_cli=$(command -v cosift 2>/dev/null || :)
	if [ -z "$_cli" ]; then
		warn "The Cosift CLI is not installed; your agent connection is ready."
		warn "Install a signed CLI release from https://github.com/pilot-protocol/cosift/releases, then rerun install.sh --cli."
		if [ "$OPT_CLI" = required ]; then return 1; fi
		return 0
	fi
	if [ -e "$CLI_SESSION_FILE" ] || [ -L "$CLI_SESSION_FILE" ]; then
		warn "Existing CLI session left unchanged: $CLI_SESSION_FILE"
		warn "To switch it, run cosift logout before rerunning the installer. Logout also revokes that token in any agents sharing it."
		if [ "$OPT_CLI" = required ]; then return 1; fi
		return 0
	fi
	"$_cli" login -help >"$TMPD/cli-help" 2>&1 || :
	if ! grep -q -- '-session-file' "$TMPD/cli-help"; then
		warn "The installed cosift does not support shared CLI sessions; install the current signed release and rerun install.sh --cli."
		if [ "$OPT_CLI" = required ]; then return 1; fi
		return 0
	fi
	if ! mkdir -p "$STATE_DIR"; then
		warn "Could not create the CLI session directory: $STATE_DIR"
		if [ "$OPT_CLI" = required ]; then return 1; fi
		return 0
	fi
	step "Connecting the Cosift CLI to $COSIFT_COMMUNITY_URL"
	if COSIFT_TOKEN="$TOKEN" COSIFT_SESSION_FILE='' COSIFT_EMAIL='' COSIFT_PASSWORD='' \
		"$_cli" login -server "$COSIFT_COMMUNITY_URL" -session-file "$CLI_SESSION_FILE" \
		>"$TMPD/cli-login" 2>&1; then
		CLI_CONNECTED=1
		ok "CLI session saved in $CLI_SESSION_FILE (0600)."
		if [ -n "${COSIFT_TOKEN:-}${COSIFT_EMAIL:-}${COSIFT_PASSWORD:-}${COSIFT_SESSION_FILE:-}" ]; then
			warn "Your existing COSIFT_TOKEN, COSIFT_EMAIL, COSIFT_PASSWORD or COSIFT_SESSION_FILE environment takes precedence. Unset those selectors to use the installed session."
		fi
		return 0
	fi
	warn "The agent is configured, but the CLI could not connect:"
	redact <"$TMPD/cli-login" >&2
	if [ "$OPT_CLI" = required ]; then return 1; fi
	return 0
}

summary() {
	say ""
	say "${CLR_OK}${OK_MARK}Cosift is connected.${CLR_RESET}"
	for _h in $CONFIGURED; do
		printf '  %-16s %s%s%s\n' "$(harness_label "$_h")" \
			"$CLR_DIM" "$(harness_config_path "$_h")" "$CLR_RESET"
	done
	# Short, but never silent: these files did not hold a credential before we ran.
	say "  $(dim "Those files now hold your Cosift credential.")"
	say "Web account  $COSIFT_COMMUNITY_URL (use the same email as your agents)"
	if [ "$CLI_CONNECTED" -eq 1 ]; then
		say "CLI ready    cosift request -query 'Your question'"
		say "Contribute   cosift contribute https://example.org/article"
		say "Credits      cosift contribute -credits"
	fi
	if [ -n "$TIGHTENED" ]; then
		say "  $(dim "Tightened to 0600, having been readable by others:")"
		printf '%s\n' "$TIGHTENED" | sed -e "s/^/    $CLR_DIM/" -e "s/\$/$CLR_RESET/"
	fi
	say ""
	if [ -n "$ONBOARDED" ]; then
		for _h in $ONBOARDED; do
			if [ "$_h" = claude ] && [ "$CLAUDE_HOOKED" -eq 1 ]; then
				say "Setup starts on its own next time you open $(harness_label "$_h")."
			else
				say "To set up, type ${CLR_ASK}$(onboarding_invocation "$_h")${CLR_RESET} in $(harness_label "$_h")."
			fi
		done
		if ! onboarding_on_path; then
			say "Add $(dim "$LOCAL_BIN") to your PATH so it can record that you are done:"
			say "  export PATH=\"\$HOME/.local/bin:\$PATH\""
		fi
		say ""
	fi
	say "Undo         install.sh --uninstall   $(dim "(revoke the credential in your account)")"
	say "What it did  ${CLR_DIM}$WHAT_HAPPENS_URL${CLR_RESET}"
}

# Each opening prompt is the harness's own documented way in: claude takes a bare
# prompt, codex takes [PROMPT], opencode takes --prompt.
launch_hint() {
	case "$1" in
	claude) printf '%s\n' 'claude "set up cosift"' ;;
	codex) printf '%s\n' "codex '\$cosift-onboarding'" ;;
	opencode) printf '%s\n' "opencode --prompt '/cosift-onboarding'" ;;
	*) return 1 ;;
	esac
}

# Under `curl | sh` stdin is the script, so the harness has to be handed the terminal.
launch_exec() {
	case "$1" in
	claude) exec claude "set up cosift" </dev/tty ;;
	codex) exec codex "\$cosift-onboarding" </dev/tty ;;
	opencode) exec opencode --prompt '/cosift-onboarding' </dev/tty ;;
	esac
}

# The start-up hook fires but an agent has no turn to act in until the user types
# something, so the install ends by offering to open one with an opening prompt.
launch_offer() {
	if [ "$OPT_LAUNCH" -eq 0 ] || [ "$OPT_YES" -eq 1 ] || [ -z "$ONBOARDED" ]; then
		return 0
	fi
	if [ ! -t 1 ] || ! tty_usable; then return 0; fi
	_cands=""
	for _h in $ONBOARDED; do
		if have_cmd "$_h" && launch_hint "$_h" >/dev/null; then
			_cands=$(list_add "$_cands" "$_h")
		fi
	done
	if [ -z "$_cands" ]; then return 0; fi
	_pick=""
	case "$_cands" in
	*" "*)
		say ""
		say "${CLR_HEAD}Finish setting up now?${CLR_RESET} We can open one of them for you:"
		_i=0
		for _h in $_cands; do
			_i=$((_i + 1))
			printf '  %s) %s\n' "$_i" "$(harness_label "$_h")"
		done
		if ! tty_ask "Which? [1-$_i, Enter = 1, n = not now]: "; then return 0; fi
		case "$TTY_REPLY" in
		"") _pick=${_cands%% *} ;;
		[0-9]*)
			_i=0
			for _h in $_cands; do
				_i=$((_i + 1))
				if [ "$_i" = "$TTY_REPLY" ]; then _pick=$_h; fi
			done
			;;
		*)
			if in_list "$TTY_REPLY" "$_cands"; then _pick=$TTY_REPLY; fi
			;;
		esac
		;;
	*)
		_pick=$_cands
		if ! tty_ask "Open $(harness_label "$_pick") and finish setting up now? [Y/n]: "; then
			return 0
		fi
		case "$TTY_REPLY" in
		"" | y | Y | yes | YES | Yes) ;;
		*) _pick="" ;;
		esac
		;;
	esac
	if [ -z "$_pick" ]; then return 0; fi
	say ""
	# exec leaves nothing behind to print a fallback, and nothing to clean up either.
	say "Opening $(harness_label "$_pick") - if it does not start, run: $(dim "$(launch_hint "$_pick")")"
	cleanup
	launch_exec "$_pick"
}

onboarding_dry_run() {
	if [ "$OPT_ONBOARDING" = 0 ]; then return 0; fi
	_op=$(onboarding_path "$1") || return 0
	say "  interview: $(dim "$_op")"
	if [ "$1" = opencode ] && _orival=$(onboarding_opencode_rival); then
		say "             $_orival already claims that command name, so"
		say "             the interview would be skipped here (a warning, not a failure)"
		return 0
	fi
	if [ -L "$_op" ]; then
		say "             that path is a symlink, so it would be refused and left alone"
	else
		case "$(onboarding_state "$1")" in
		ours) say "             already byte-identical to ours; it would be left unchanged" ;;
		stale) say "             an older copy of ours is there; it would be replaced in place" ;;
		foreign) say "             a file we did not write is there; it would be backed up, then replaced" ;;
		*) say "             nothing there yet; it would be installed (mode 0644)" ;;
		esac
	fi
	if [ "$1" = claude ]; then
		say "  settings:  $(dim "$CLAUDE_SETTINGS")"
		say "             one SessionStart hook and the four cosift tool permissions,"
		say "             appended; every other key in that file is left as it is"
	fi
	return 0
}

dry_run() {
	step "Dry run - nothing will be written"
	if [ "$OPT_CLI" != no ]; then
		say "CLI: an installed cosift would verify this token at $COSIFT_COMMUNITY_URL"
		say "     and create $CLI_SESSION_FILE (0600); existing files stay untouched."
	fi
	say ""
	if [ "$OPT_NEW_ACCOUNT" -eq 1 ]; then
		say "Token source: a new account. Any credential already on this machine is left"
		say "              alone, and you would be asked for your email and a 6-digit code."
	elif try_recover_token; then
		say "Token source: an existing credential on this machine would be reused."
		say "              No email verification would be needed."
	else
		say "Token source: no usable credential found, so the installer would ask for"
		say "              your email address and a 6-digit code. (Not doing that now.)"
	fi
	say ""
	for _h in $SELECTED; do
		_cfg=$(harness_config_path "$_h")
		say "${CLR_HEAD}$(harness_label "$_h")${CLR_RESET} [$_h]"
		say "  config:  $(dim "$_cfg")"
		if [ -n "$TOKEN" ] && harness_up_to_date "$_h" "$TOKEN"; then
			say "  backup:  none (nothing would be written)"
			say "  status:  already holds this credential; it would be left untouched"
			onboarding_dry_run "$_h"
			say ""
			continue
		fi
		if [ -f "$_cfg" ]; then
			say "  backup:  $(dim "$_cfg.cosift-backup-<UTC timestamp>")"
		else
			say "  backup:  none (file does not exist yet, it would be created)"
		fi
		if harness_is_configured "$_h"; then
			say "  status:  a cosift entry is already present; it would be replaced"
		else
			say "  status:  no cosift entry yet; it would be added"
		fi
		case "$_h" in
		claude)
			say "  action:  claude mcp add --transport http --scope user cosift \\"
			say "             '$COSIFT_MCP_URL' --header 'Authorization: Bearer ck_...'"
			;;
		codex)
			say "  action:  append a marker-delimited [mcp_servers.cosift] block:"
			say "             $CODEX_MARK_OPEN"
			say "             [mcp_servers.cosift]"
			say "             url = \"$COSIFT_MCP_URL\""
			say "             [mcp_servers.cosift.http_headers]"
			say "             Authorization = \"Bearer ck_...\""
			say "             $CODEX_MARK_CLOSE"
			if codex_foreign_table; then
				say "  ${CLR_WARN}WARNING:${CLR_RESET} an [mcp_servers.cosift] table already exists outside our"
				say "           markers - a real run would refuse (exit 5)."
			fi
			;;
		opencode)
			say "  action:  opencode mcp add cosift --url '$COSIFT_MCP_URL' \\"
			say "             --header 'Authorization=Bearer ck_...'"
			if ! have_cmd opencode; then
				say "  ${CLR_WARN}WARNING:${CLR_RESET} opencode is not on PATH - a real run would refuse (exit 5)."
			fi
			;;
		esac
		if [ -n "$COSIFT_EXTRA_HEADER" ]; then
			say "  extra:   ${COSIFT_EXTRA_HEADER%%:*} would also be written into the config"
		fi
		onboarding_dry_run "$_h"
		say ""
	done
	say "State that would be written: $(dim "$STATE_FILE") (mode 0600)"
	if [ "$OPT_ONBOARDING" = 0 ]; then
		say "Onboarding interview: not installed (--no-onboarding)."
	else
		say "Onboarding state command: $(dim "$ONBOARDING_CMD") (mode 0755)"
		say "The interview starts by itself in Claude Code; in codex and opencode you"
		say "type its name."
		say "A real run then offers once to open a harness on a prompt that starts the"
		say "interview; --no-launch and --yes skip that question."
		if [ -z "$OPT_ONBOARDING" ]; then
			say "The interview is written only if you say yes to the question asked after"
			say "the harness list; --onboarding answers it up front, --no-onboarding declines."
		fi
		if ! onboarding_on_path; then
			say "Note: $(dim "$LOCAL_BIN") is not on your PATH, so the interview could not run"
			say "      cosift-onboarding until it is."
		fi
	fi
	say "Nothing was written. Re-run without --dry-run to apply."
	exit "$EX_OK"
}

do_install() {
	step "cosift-install $VERSION"
	say "    $(dim "$COSIFT_MCP_URL")"
	preflight
	if [ "$OPT_DRY_RUN" -eq 0 ] && [ -z "$OPT_HARNESS" ] && [ "$OPT_YES" -eq 0 ]; then
		require_tty
	fi
	detect_all
	detection_report
	if [ -z "$DETECTED" ] && [ -z "$OPT_HARNESS" ]; then
		err "no supported AI harness found on this machine."
		err "cosift-install can configure Claude Code, the OpenAI Codex CLI and opencode."
		err "install one of them and re-run, or pass --harness=<name> if you know the"
		err "config exists somewhere we did not look."
		exit "$EX_PREFLIGHT"
	fi
	select_harnesses
	if [ "$OPT_DRY_RUN" -eq 1 ]; then
		dry_run
	fi
	obtain_token
	configure_harnesses
	if final_verify; then
		if ! community_cli_step; then
			exit "$EX_HARNESS"
		fi
	fi
	if ! write_state; then
		exit "$EX_HARNESS"
	fi
	summary
	launch_offer
	exit "$EX_OK"
}

onboarding_uninstall() {
	step "Removing the onboarding interview"
	# The state file is a hint, not the authority: a later run with different flags
	# rewrites onboarding_installed, and anything dropped from it would be stranded on
	# disk with no record that we put it there. Our own artifacts are self-identifying,
	# so ask the disk as well.
	_otargets=$1
	for _oh in claude codex opencode; do
		case "$(onboarding_state "$_oh" 2>/dev/null)" in
		ours | stale) _otargets=$(list_add "$_otargets" "$_oh") ;;
		esac
	done
	for _oh in $_otargets; do
		case "$_oh" in
		claude | codex | opencode) ;;
		*) continue ;;
		esac
		if ! onboarding_remove "$_oh"; then
			warn "could not remove the onboarding interview for $_oh; remove it by hand:"
			warn "  $(onboarding_path "$_oh")"
		fi
	done
	if ! onboarding_cmd_remove; then
		warn "remove $ONBOARDING_CMD by hand."
	fi
	claude_settings_remove || :
	if [ -f "$ONBOARDING_STATE_FILE" ]; then
		if rm -f "$ONBOARDING_STATE_FILE"; then
			ok "removed $(dim "$ONBOARDING_STATE_FILE")"
		else
			warn "could not remove $ONBOARDING_STATE_FILE"
		fi
	fi
	return 0
}

do_uninstall() {
	step "cosift-install $VERSION - removing cosift"
	preflight
	_targets=$(state_harnesses 2>/dev/null)
	if [ -z "$_targets" ]; then
		if [ -f "$STATE_FILE" ]; then
			say "$(dim "$STATE_FILE") names no harness we can read; looking for our entries directly."
		else
			say "No state file at $(dim "$STATE_FILE"); looking for our entries directly."
		fi
		for _h in claude codex opencode; do
			if harness_is_configured "$_h"; then
				_targets=$(list_add "$_targets" "$_h")
			fi
		done
	fi
	# Removing the interview first keeps a failed harness removal from stranding it.
	if ! _onb=$(state_onboarded); then
		_onb=$_targets
	fi
	onboarding_uninstall "$_onb"
	if [ -z "$_targets" ]; then
		say "Nothing to remove: no cosift entry found in any supported harness."
		if [ -f "$STATE_FILE" ]; then
			rm -f "$STATE_FILE"
			say "Removed $STATE_FILE"
		fi
		exit "$EX_OK"
	fi
	_failed=""
	for _h in $_targets; do
		case "$_h" in
		claude | codex | opencode) ;;
		*)
			warn "state names an unknown harness '$_h'; skipping."
			continue
			;;
		esac
		step "Removing cosift from $(harness_label "$_h")"
		BACKUP_PATH=""
		if harness_remove "$_h"; then
			if [ -n "$BACKUP_PATH" ]; then
				say "    backup $(dim "$BACKUP_PATH")"
			fi
		else
			_failed=$(list_add "$_failed" "$_h")
		fi
	done
	if [ -n "$_failed" ]; then
		err "could not remove the cosift entry from: $_failed"
		err "the state file was left in place so you can retry."
		exit "$EX_HARNESS"
	fi
	if [ -f "$STATE_FILE" ]; then
		if ! rm -f "$STATE_FILE"; then
			err "could not remove $STATE_FILE"
			exit "$EX_HARNESS"
		fi
	fi
	say ""
	say "${CLR_OK}${OK_MARK}Removed.${CLR_RESET} A backup of each config was left next to it. The credential is"
	say "still valid server-side - revoke it in your Cosift account if you want it dead."
	exit "$EX_OK"
}

parse_args() {
	_want_onb=0
	_skip_onb=0
	_want_cli=0
	_skip_cli=0
	if [ -n "${COSIFT_NO_LAUNCH+set}" ]; then OPT_LAUNCH=0; fi
	while [ $# -gt 0 ]; do
		case "$1" in
		--dry-run) OPT_DRY_RUN=1 ;;
		--uninstall) OPT_UNINSTALL=1 ;;
		--yes) OPT_YES=1 ;;
		--onboarding) _want_onb=1 ;;
		--no-onboarding) _skip_onb=1 ;;
		--no-launch) OPT_LAUNCH=0 ;;
		--new-account) OPT_NEW_ACCOUNT=1 ;;
		--cli) _want_cli=1 ;;
		--no-cli) _skip_cli=1 ;;
		--harness=*)
			OPT_HARNESS=${1#--harness=}
			if [ -z "$OPT_HARNESS" ]; then
				usage >&2
				exit "$EX_USAGE"
			fi
			for _h in $(printf '%s\n' "$OPT_HARNESS" | tr ',' ' '); do
				case "$_h" in
				claude | codex | opencode) ;;
				*)
					err "unknown harness: $_h (expected claude, codex or opencode)"
					usage >&2
					exit "$EX_USAGE"
					;;
				esac
			done
			;;
		--help)
			usage
			exit "$EX_OK"
			;;
		--version)
			say "cosift-install $VERSION"
			exit "$EX_OK"
			;;
		*)
			err "unknown option: $1"
			usage >&2
			exit "$EX_USAGE"
			;;
		esac
		shift
	done
	if [ "$OPT_DRY_RUN" -eq 1 ] && [ "$OPT_UNINSTALL" -eq 1 ]; then
		err "--dry-run and --uninstall cannot be combined."
		usage >&2
		exit "$EX_USAGE"
	fi
	if [ "$_want_onb" -eq 1 ] && [ "$_skip_onb" -eq 1 ]; then
		err "--onboarding and --no-onboarding cannot be combined."
		usage >&2
		exit "$EX_USAGE"
	fi
	if [ "$_want_cli" -eq 1 ] && [ "$_skip_cli" -eq 1 ]; then
		err "--cli and --no-cli cannot be combined."
		exit "$EX_USAGE"
	fi
	if [ "$_skip_cli" -eq 1 ]; then
		OPT_CLI=no
	elif [ "$_want_cli" -eq 1 ]; then
		OPT_CLI=required
	fi
	if [ "$_skip_onb" -eq 1 ]; then
		OPT_ONBOARDING=0
	elif [ "$_want_onb" -eq 1 ] || [ "$OPT_YES" -eq 1 ]; then
		OPT_ONBOARDING=1
	fi
}

main() {
	init_colour
	parse_args "$@"
	init_tmp
	if [ "$OPT_UNINSTALL" -eq 1 ]; then
		do_uninstall
	fi
	do_install
}

main "$@"
