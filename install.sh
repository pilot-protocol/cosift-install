	_cfg=$(opencode_config_path)
	[ -f "$_cfg" ] || return 1
	_e=$(opencode_jsonc entry "$_cfg" 2>/dev/null) || return 1
	if [ -z "$_e" ]; then return 1; fi
	case "$_e" in
	*"$COSIFT_MCP_URL"*) ;;
	*) return 1 ;;
	esac
