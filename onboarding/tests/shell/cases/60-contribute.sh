#!/bin/sh
# The cosift-contribute artifact: all four profiles are generated, the drift gate guards them,
# and the body teaches guide, then join with consent, then submit.
set -u
# shellcheck disable=SC1091
. "$(dirname -- "$0")/00-lib.sh"

GEN_REL=contribute/generated
BODY="$ONB_ROOT/contribute/BODY.md"
MANIFEST="$ONB_ROOT/$GEN_REL/MANIFEST.json"
GENERATOR="$ONB_ROOT/tools/generate.py"
EXPECTED_HARNESSES="claude codex hermes opencode"

[ -f "$GENERATOR" ] || skip_case "tools/generate.py is missing"

if [ ! -f "$BODY" ] || [ ! -f "$MANIFEST" ]; then
    fail_note "contribute/BODY.md or $GEN_REL/MANIFEST.json is missing"
    finish
fi

python3 "$GENERATOR" --artifact cosift-contribute --check >"$ONB_TMP/check.out" 2>&1
assert_true $? "generate.py --artifact cosift-contribute --check exits 0" "$(cat "$ONB_TMP/check.out")"

assert_eq "cosift-contribute" "$(manifest_top "$MANIFEST" artifact)" "manifest names the artifact"
assert_eq "contribute/BODY.md" "$(manifest_top "$MANIFEST" body_source)" "manifest names its body source"
assert_eq "$EXPECTED_HARNESSES" "$(manifest_harnesses "$MANIFEST")" "all four profiles are generated"

BODY_SHA=$(sha256_of "$BODY")
BODY_SIZE=$(file_size "$BODY")
assert_eq "$BODY_SHA" "$(manifest_top "$MANIFEST" body_sha256)" "manifest body_sha256 matches contribute/BODY.md"

for harness in $EXPECTED_HARNESSES; do
    relpath=$(manifest_field "$MANIFEST" "$harness" generated_path)
    generated="$ONB_ROOT/$relpath"
    if [ ! -f "$generated" ]; then
        fail_note "$harness generated file is missing" "$generated"
        continue
    fi
    prefix_bytes=$(manifest_field "$MANIFEST" "$harness" prefix_bytes)
    assert_eq "$(manifest_field "$MANIFEST" "$harness" sha256)" "$(sha256_of "$generated")" \
        "$harness generated sha256 matches the manifest"
    assert_eq "$((prefix_bytes + BODY_SIZE))" "$(file_size "$generated")" \
        "$harness file size is prefix_bytes plus the body size"
    tail -c "+$((prefix_bytes + 1))" -- "$generated" >"$ONB_TMP/body.$harness"
    assert_same_bytes "$ONB_TMP/body.$harness" "$BODY" "$harness body is byte-identical to contribute/BODY.md"
    if grep -q "^<!-- generated by .*contribute/BODY\.md; cosift-contribute v[0-9.]*; do not edit -->$" "$generated"; then
        pass_note "$harness marker names the source and the artifact"
    else
        fail_note "$harness marker does not name contribute/BODY.md and cosift-contribute"
    fi
    install_path=$(manifest_field "$MANIFEST" "$harness" install_path)
    case "$install_path" in
        *cosift-contribute*) pass_note "$harness installs under cosift-contribute" ;;
        *) fail_note "$harness install path is not cosift-contribute's" "$install_path" ;;
    esac
    case "$install_path" in
        *cosift-onboarding*) fail_note "$harness install path collides with the interview" "$install_path" ;;
        *) pass_note "$harness install path does not collide with the interview" ;;
    esac
    assert_eq "$(profile_keys_sorted "$ONB_ROOT/contribute/profiles/$harness.json" allowed_frontmatter_keys)" \
        "$(frontmatter_keys "$generated" | LC_ALL=C sort | tr '\n' ' ' | sed 's/ *$//')" \
        "$harness frontmatter key set equals its allowed set"
done

CODEX_FILE="$ONB_ROOT/$(manifest_field "$MANIFEST" codex generated_path)"
assert_eq "description name" \
    "$(frontmatter_keys "$CODEX_FILE" | LC_ALL=C sort | tr '\n' ' ' | sed 's/ *$//')" \
    "codex frontmatter is ONLY name and description"

# --- the body teaches the flow, in order, with the consent gate ---------------------------

line_of() { grep -n -F -m1 -e "$1" "$BODY" | cut -d: -f1; }

for needle in 'cosift_contribute' 'guide' 'join' 'submit' 'consent_text' 'consent: true' 'recent_outcomes'; do
    if grep -q -F -e "$needle" "$BODY"; then
        pass_note "body names $needle"
    else
        fail_note "body never names $needle"
    fi
done

g=$(line_of '## Guide'); j=$(line_of '## Join'); s=$(line_of '## Submit')
if [ -n "$g" ] && [ -n "$j" ] && [ -n "$s" ] && [ "$g" -lt "$j" ] && [ "$j" -lt "$s" ]; then
    pass_note "the sections run Guide, Join, Submit"
else
    fail_note "the sections do not run Guide, Join, Submit" "guide=$g join=$j submit=$s"
fi

if grep -q -i 'only after the user has agreed' "$BODY"; then
    pass_note "body makes consent the user's, given in the conversation"
else
    fail_note "body does not say consent is passed only after the user has agreed"
fi
if grep -q 'Never join on your own' "$BODY"; then
    pass_note "body forbids joining on the agent's own initiative"
else
    fail_note "body does not forbid joining on the agent's own initiative"
fi

section() { awk -v h="## $1" '$0 == h { f = 1; next } /^## / { f = 0 } f' "$BODY"; }

section Join >"$ONB_TMP/join.sec"
cl=$(grep -n -F -m1 'consent_text' "$ONB_TMP/join.sec" | cut -d: -f1)
ct=$(grep -n -F -m1 'consent: true' "$ONB_TMP/join.sec" | cut -d: -f1)
if [ -n "$cl" ] && [ -n "$ct" ] && [ "$cl" -lt "$ct" ]; then
    pass_note "join shows consent_text before it passes consent: true"
else
    fail_note "join does not show consent_text before consent: true" "consent_text=$cl consent=$ct"
fi
yes=$(grep -n -F -m1 'Only after a clear yes' "$ONB_TMP/join.sec" | cut -d: -f1)
if [ -n "$yes" ] && [ -n "$cl" ] && [ -n "$ct" ] && [ "$cl" -lt "$yes" ] && [ "$yes" -le "$ct" ]; then
    pass_note "join waits for a clear yes between consent_text and consent: true"
else
    fail_note "join does not wait for a clear yes before consent: true" "yes=$yes"
fi

section Submit >"$ONB_TMP/submit.sec"
if grep -q 'the title, the lead, the body and the sources' "$ONB_TMP/submit.sec" &&
    grep -q 'Never submit anything the user has not seen\. Show .*the body' "$BODY"; then
    pass_note "the approval shows the whole submission, body included"
else
    fail_note "the approval step does not show the body"
fi

if grep -n -E 'https?://' "$BODY" >"$ONB_TMP/urls.out"; then
    fail_note "body names a URL (the guide hands out every address)" "$(cat "$ONB_TMP/urls.out")"
else
    pass_note "body names no URL"
fi

# --- the drift gate catches each kind of drift --------------------------------------------

scratch_root() { # name -> prints a copy of the generator's inputs
    _r="$ONB_TMP/$1"
    mkdir -p "$_r"
    cp -R "$ONB_ROOT/tools" "$ONB_ROOT/contribute" "$ONB_ROOT/VERSION" "$ONB_ROOT/profiles" \
        "$ONB_ROOT/interview" "$ONB_ROOT/generated" "$_r/"
    printf '%s\n' "$_r"
}

r=$(scratch_root edited-body)
printf '\nAn extra line.\n' >>"$r/contribute/BODY.md"
python3 "$r/tools/generate.py" --root "$r" --artifact cosift-contribute --check >/dev/null 2>&1
assert_eq "1" "$?" "an edited body without regenerating fails the gate"

r=$(scratch_root edited-output)
printf 'x' >>"$r/$GEN_REL/claude/cosift-contribute/SKILL.md"
python3 "$r/tools/generate.py" --root "$r" --artifact cosift-contribute --check >/dev/null 2>&1
assert_eq "1" "$?" "an edited generated file fails the gate"

r=$(scratch_root missing-output)
rm "$r/$GEN_REL/opencode/cosift-contribute.md"
python3 "$r/tools/generate.py" --root "$r" --artifact cosift-contribute --check >/dev/null 2>&1
assert_eq "1" "$?" "a missing generated file fails the gate"

r=$(scratch_root regenerated)
printf '\nAn extra line.\n' >>"$r/contribute/BODY.md"
python3 "$r/tools/generate.py" --root "$r" --artifact cosift-contribute --quiet >/dev/null 2>&1
python3 "$r/tools/generate.py" --root "$r" --artifact cosift-contribute --check >/dev/null 2>&1
assert_eq "0" "$?" "regenerating after an edit passes the gate"

python3 "$GENERATOR" --check >"$ONB_TMP/all.out" 2>&1
assert_true $? "the default check covers both artifacts and passes" "$(cat "$ONB_TMP/all.out")"
if grep -q 'cosift-onboarding' "$ONB_TMP/all.out" && grep -q 'cosift-contribute' "$ONB_TMP/all.out"; then
    pass_note "the default check reports both artifacts"
else
    fail_note "the default check does not report both artifacts" "$(cat "$ONB_TMP/all.out")"
fi

finish
